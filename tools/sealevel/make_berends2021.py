"""Build sealevel_record.js from the Berends et al. (2021) supplement.

Source data (CC BY 4.0): https://doi.org/10.5281/zenodo.3793592
  file Berends_etal_2020_CP_supplement.dat (100-yr steps, 3.6 Myr to present)
Usage: python3 tools/sealevel/make_berends2021.py path/to/Berends_etal_2020_CP_supplement.dat
Keeps the central estimate (SL column) at whole kyr: 3600 values, 3599 ka ago .. 0.
"""
import sys
rows = {}
for line in open(sys.argv[1]):
    if line.startswith('%') or not line.strip():
        continue
    t, sl = line.split()[:2]
    t10 = round(float(t) * 10)          # time in 0.1 kyr steps (negative = ago)
    if t10 % 10 == 0:
        rows[-t10 // 10] = float(sl)    # ka ago -> m relative to present
vals = [rows[k] for k in range(3599, -1, -1)]
body = ','.join(('%.2f' % v).rstrip('0').rstrip('.') for v in vals)
out = f"""/* Global mean sea level over the last 3.6 Myr (3599 ka to present), from
   Berends, C. J., de Boer, B., and van de Wal, R. S. W. (2021): Reconstructing the evolution of
   ice sheets, sea level, and atmospheric CO2 during the past 3.6 million years.
   Climate of the Past 17, 361-377. https://doi.org/10.5194/cp-17-361-2021
   Data: https://doi.org/10.5281/zenodo.3793592 (CC BY 4.0). Central estimate, resampled to
   whole kyr. Generated by tools/sealevel/make_berends2021.py; do not edit by hand.
   UMD: window.SeaLevelRecord in the browser, module.exports in Node. */
(function (root, factory) {{
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else root.SeaLevelRecord = factory();
}})(typeof self !== 'undefined' ? self : this, function () {{
  'use strict';
  // values[k] = sea level (m, relative to present) at (startKaAgo - k*stepKa) ka before present
  var values = [{body}];
  return {{
    name: 'Berends et al. (2021)',
    citation: 'Berends, de Boer & van de Wal (2021), Climate of the Past 17, 361-377',
    url: 'https://doi.org/10.5194/cp-17-361-2021',
    dataUrl: 'https://doi.org/10.5281/zenodo.3793592',
    licence: 'CC BY 4.0',
    startKaAgo: 3599, stepKa: 1, values: values,
    /* sea level (m rel. present) at a time in ka before present, linear between kyr samples */
    at: function (kaAgo) {{
      var u = Math.max(0, Math.min(3599, 3599 - kaAgo)), j = Math.min(3598, Math.floor(u)), f = u - j;
      return values[j] + f * (values[j + 1] - values[j]);
    }}
  }};
}});
"""
open('sealevel_record.js', 'w').write(out)
print(len(vals), 'values, min', min(vals), 'max', max(vals), len(out), 'bytes')
